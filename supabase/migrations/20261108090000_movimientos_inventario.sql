    ON inventario.movimiento (movimiento_anulado_id)
    WHERE tipo = 'ANULACION';

-- ---------------------------------------------------------------------------
-- 3. Validación interna de cantidad y unidad.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION inventario.validar_cantidad_movimiento(
    p_producto_id uuid,
    p_cantidad numeric
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
    v_admite_decimales boolean;
BEGIN
    IF p_cantidad IS NULL OR p_cantidad <= 0 THEN
        RAISE EXCEPTION 'CANTIDAD_INVALIDA' USING ERRCODE = '22023';
    END IF;

    SELECT um.admite_decimales
    INTO v_admite_decimales
    FROM inventario.producto AS pr
    JOIN inventario.unidad_medida AS um
      ON um.id = pr.unidad_medida_id
    WHERE pr.id = p_producto_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'PRODUCTO_NO_EXISTE' USING ERRCODE = 'P0002';
    END IF;

    IF v_admite_decimales = false AND p_cantidad <> trunc(p_cantidad) THEN
        RAISE EXCEPTION 'UNIDAD_NO_ADMITE_DECIMALES' USING ERRCODE = '22023';
    END IF;
END;
$function$;

-- ---------------------------------------------------------------------------
-- 4. Registrar entrada.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION inventario.registrar_entrada(
    p_idempotency_key uuid,
    p_producto_id uuid,
    p_cantidad numeric,
    p_motivo_codigo text,
    p_costo_unitario numeric DEFAULT NULL,
    p_proveedor_id uuid DEFAULT NULL,
    p_observacion text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
    v_usuario uuid;
    v_producto inventario.producto%ROWTYPE;
    v_movimiento inventario.movimiento%ROWTYPE;
    v_motivo inventario.motivo_movimiento%ROWTYPE;
    v_nuevo_stock numeric(14,3);
    v_nuevo_costo numeric(14,4);
    v_estado text;
    v_codigo varchar(30);
BEGIN
    v_usuario := auth.uid();
    IF v_usuario IS NULL THEN
        RAISE EXCEPTION 'NO_AUTENTICADO' USING ERRCODE = '28000';
    END IF;
    IF NOT seguridad.tiene_permiso('movimiento.registrar_entrada') THEN
        RAISE EXCEPTION 'SIN_PERMISO' USING ERRCODE = '42501';
    END IF;
    IF p_idempotency_key IS NULL THEN
        RAISE EXCEPTION 'IDEMPOTENCY_KEY_OBLIGATORIA' USING ERRCODE = '22023';
    END IF;
    IF p_observacion IS NOT NULL AND char_length(p_observacion) > 280 THEN
        RAISE EXCEPTION 'OBSERVACION_INVALIDA' USING ERRCODE = '22023';
    END IF;

    -- Serializa solicitudes concurrentes que compartan la misma clave.
    PERFORM pg_catalog.pg_advisory_xact_lock(
        pg_catalog.hashtextextended(p_idempotency_key::text, 0)
    );

    v_codigo := upper(btrim(p_motivo_codigo));
    SELECT * INTO v_movimiento
    FROM inventario.movimiento
    WHERE idempotency_key = p_idempotency_key;
    IF FOUND THEN
        IF v_movimiento.registrado_por IS DISTINCT FROM v_usuario
           OR v_movimiento.tipo <> 'ENTRADA'
           OR v_movimiento.producto_id IS DISTINCT FROM p_producto_id
           OR v_movimiento.cantidad IS DISTINCT FROM p_cantidad
           OR v_movimiento.motivo_codigo IS DISTINCT FROM v_codigo
           OR v_movimiento.costo_unitario IS DISTINCT FROM p_costo_unitario
           OR v_movimiento.proveedor_id IS DISTINCT FROM p_proveedor_id
           OR v_movimiento.observacion IS DISTINCT FROM p_observacion THEN
            RAISE EXCEPTION 'IDEMPOTENCY_KEY_EN_USO' USING ERRCODE = '23505';
        END IF;
        SELECT estado INTO v_estado
        FROM inventario.producto WHERE id = v_movimiento.producto_id;
        RETURN jsonb_build_object(
            'movimiento', to_jsonb(v_movimiento),
            'saldo', v_movimiento.saldo_resultante::text,
            'estado', v_estado
        );
    END IF;

    IF p_cantidad IS NULL OR p_cantidad <= 0 THEN
        RAISE EXCEPTION 'CANTIDAD_INVALIDA' USING ERRCODE = '22023';
    END IF;
    SELECT * INTO v_motivo
    FROM inventario.motivo_movimiento
    WHERE codigo = v_codigo AND activo = true AND aplica_a = 'ENTRADA';
    IF NOT FOUND THEN
        RAISE EXCEPTION 'MOTIVO_ENTRADA_INVALIDO' USING ERRCODE = '22023';
    END IF;
    IF v_codigo = 'COMPRA' AND p_costo_unitario IS NULL THEN
        RAISE EXCEPTION 'COSTO_UNITARIO_OBLIGATORIO' USING ERRCODE = '22023';
    END IF;
    IF p_costo_unitario IS NOT NULL AND p_costo_unitario < 0 THEN
        RAISE EXCEPTION 'COSTO_UNITARIO_INVALIDO' USING ERRCODE = '22023';
    END IF;
    IF v_codigo <> 'COMPRA' AND p_costo_unitario IS NOT NULL THEN
        RAISE EXCEPTION 'COSTO_NO_APLICA_A_MOTIVO' USING ERRCODE = '22023';
    END IF;
    IF p_proveedor_id IS NOT NULL AND v_codigo <> 'COMPRA' THEN
        RAISE EXCEPTION 'PROVEEDOR_SOLO_APLICA_A_COMPRA' USING ERRCODE = '22023';
    END IF;

    SELECT * INTO v_producto
    FROM inventario.producto
    WHERE id = p_producto_id
    FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'PRODUCTO_NO_EXISTE' USING ERRCODE = 'P0002';
    END IF;
    PERFORM inventario.validar_cantidad_movimiento(p_producto_id, p_cantidad);

    v_nuevo_stock := v_producto.stock_actual + p_cantidad;
    v_nuevo_costo := v_producto.costo_promedio;
    IF v_codigo = 'COMPRA' THEN
        v_nuevo_costo := (
            v_producto.stock_actual * v_producto.costo_promedio
            + p_cantidad * p_costo_unitario
        ) / NULLIF(v_nuevo_stock, 0);
    END IF;

    UPDATE inventario.producto
    SET stock_actual = v_nuevo_stock,
        costo_promedio = v_nuevo_costo
    WHERE id = p_producto_id;
    SELECT estado INTO v_estado
    FROM inventario.producto WHERE id = p_producto_id;

    INSERT INTO inventario.movimiento (
        producto_id, tipo, motivo_codigo, cantidad, saldo_resultante,
        costo_unitario, costo_promedio_resultante, proveedor_id,
        observacion, registrado_por, idempotency_key,
        stock_anterior, costo_promedio_anterior
    ) VALUES (
        p_producto_id, 'ENTRADA', v_codigo, p_cantidad, v_nuevo_stock,
        p_costo_unitario, v_nuevo_costo, p_proveedor_id,
        p_observacion, v_usuario, p_idempotency_key,
        v_producto.stock_actual, v_producto.costo_promedio
    ) RETURNING * INTO v_movimiento;

    RETURN jsonb_build_object(
        'movimiento', to_jsonb(v_movimiento),
        'saldo', v_nuevo_stock::text,
        'estado', v_estado
    );
END;
$function$;

-- ---------------------------------------------------------------------------
-- 5. Registrar salida.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION inventario.registrar_salida(
    p_idempotency_key uuid,
    p_producto_id uuid,
    p_cantidad numeric,
    p_motivo_codigo text,
    p_observacion text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
    v_usuario uuid;
    v_producto inventario.producto%ROWTYPE;
    v_movimiento inventario.movimiento%ROWTYPE;
    v_motivo inventario.motivo_movimiento%ROWTYPE;
    v_nuevo_stock numeric(14,3);
    v_estado text;
    v_codigo varchar(30);
BEGIN
    v_usuario := auth.uid();
    IF v_usuario IS NULL THEN
        RAISE EXCEPTION 'NO_AUTENTICADO' USING ERRCODE = '28000';
    END IF;
    IF NOT seguridad.tiene_permiso('movimiento.registrar_salida') THEN
        RAISE EXCEPTION 'SIN_PERMISO' USING ERRCODE = '42501';
    END IF;
    IF p_idempotency_key IS NULL THEN
        RAISE EXCEPTION 'IDEMPOTENCY_KEY_OBLIGATORIA' USING ERRCODE = '22023';
    END IF;
    IF p_observacion IS NOT NULL AND char_length(p_observacion) > 280 THEN
        RAISE EXCEPTION 'OBSERVACION_INVALIDA' USING ERRCODE = '22023';
    END IF;

    PERFORM pg_catalog.pg_advisory_xact_lock(
        pg_catalog.hashtextextended(p_idempotency_key::text, 0)
    );
    v_codigo := upper(btrim(p_motivo_codigo));

    SELECT * INTO v_movimiento
    FROM inventario.movimiento
    WHERE idempotency_key = p_idempotency_key;
    IF FOUND THEN
        IF v_movimiento.registrado_por IS DISTINCT FROM v_usuario
           OR v_movimiento.tipo <> 'SALIDA'
           OR v_movimiento.producto_id IS DISTINCT FROM p_producto_id
           OR v_movimiento.cantidad IS DISTINCT FROM p_cantidad
           OR v_movimiento.motivo_codigo IS DISTINCT FROM v_codigo
           OR v_movimiento.observacion IS DISTINCT FROM p_observacion THEN
            RAISE EXCEPTION 'IDEMPOTENCY_KEY_EN_USO' USING ERRCODE = '23505';
        END IF;
        SELECT estado INTO v_estado
        FROM inventario.producto WHERE id = v_movimiento.producto_id;
        RETURN jsonb_build_object(
            'movimiento', to_jsonb(v_movimiento),
            'saldo', v_movimiento.saldo_resultante::text,
            'estado', v_estado
        );
    END IF;

    IF p_cantidad IS NULL OR p_cantidad <= 0 THEN
        RAISE EXCEPTION 'CANTIDAD_INVALIDA' USING ERRCODE = '22023';
    END IF;
    SELECT * INTO v_motivo
    FROM inventario.motivo_movimiento
    WHERE codigo = v_codigo AND activo = true AND aplica_a = 'SALIDA';
    IF NOT FOUND THEN
        RAISE EXCEPTION 'MOTIVO_SALIDA_INVALIDO' USING ERRCODE = '22023';
    END IF;

    SELECT * INTO v_producto
    FROM inventario.producto
    WHERE id = p_producto_id
    FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'PRODUCTO_NO_EXISTE' USING ERRCODE = 'P0002';
    END IF;
    PERFORM inventario.validar_cantidad_movimiento(p_producto_id, p_cantidad);
    IF v_producto.stock_actual < p_cantidad THEN
        RAISE EXCEPTION 'STOCK_INSUFICIENTE' USING ERRCODE = '23514';
    END IF;

    v_nuevo_stock := v_producto.stock_actual - p_cantidad;
    UPDATE inventario.producto
    SET stock_actual = v_nuevo_stock,
        costo_promedio = CASE WHEN v_nuevo_stock = 0 THEN 0 ELSE costo_promedio END
    WHERE id = p_producto_id;
    SELECT estado INTO v_estado
    FROM inventario.producto WHERE id = p_producto_id;

    INSERT INTO inventario.movimiento (
        producto_id, tipo, motivo_codigo, cantidad, saldo_resultante,
        costo_promedio_resultante, observacion, registrado_por,
        idempotency_key, stock_anterior, costo_promedio_anterior
    ) VALUES (
        p_producto_id, 'SALIDA', v_codigo, p_cantidad, v_nuevo_stock,
        CASE WHEN v_nuevo_stock = 0 THEN 0 ELSE v_producto.costo_promedio END,
        p_observacion, v_usuario, p_idempotency_key,
        v_producto.stock_actual, v_producto.costo_promedio
    ) RETURNING * INTO v_movimiento;

    RETURN jsonb_build_object(
        'movimiento', to_jsonb(v_movimiento),
        'saldo', v_nuevo_stock::text,
        'estado', v_estado
    );
END;
$function$;

-- ---------------------------------------------------------------------------
-- 6. Anular movimiento mediante un nuevo registro de tipo ANULACION.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION inventario.anular_movimiento(
    p_idempotency_key uuid,
    p_movimiento_id integer,
    p_motivo text,
    p_confirmacion boolean
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
    v_usuario uuid;
    v_original inventario.movimiento%ROWTYPE;
    v_existente inventario.movimiento%ROWTYPE;
    v_producto inventario.producto%ROWTYPE;
    v_anulacion inventario.movimiento%ROWTYPE;
    v_nuevo_stock numeric(14,3);
    v_nuevo_costo numeric(14,4);
    v_estado text;
BEGIN
    v_usuario := auth.uid();
    IF v_usuario IS NULL THEN
        RAISE EXCEPTION 'NO_AUTENTICADO' USING ERRCODE = '28000';
    END IF;
    IF NOT seguridad.tiene_permiso('movimiento.anular') THEN
        RAISE EXCEPTION 'SIN_PERMISO' USING ERRCODE = '42501';
    END IF;
    IF p_idempotency_key IS NULL THEN
        RAISE EXCEPTION 'IDEMPOTENCY_KEY_OBLIGATORIA' USING ERRCODE = '22023';
    END IF;
    IF p_confirmacion IS DISTINCT FROM true THEN
        RAISE EXCEPTION 'CONFIRMACION_OBLIGATORIA' USING ERRCODE = '22023';
    END IF;
    IF p_motivo IS NULL OR char_length(btrim(p_motivo)) NOT BETWEEN 5 AND 280 THEN
        RAISE EXCEPTION 'MOTIVO_ANULACION_INVALIDO' USING ERRCODE = '22023';
    END IF;

    PERFORM pg_catalog.pg_advisory_xact_lock(
        pg_catalog.hashtextextended(p_idempotency_key::text, 0)
    );
    SELECT * INTO v_existente
    FROM inventario.movimiento
    WHERE idempotency_key = p_idempotency_key;
    IF FOUND THEN
        IF v_existente.tipo <> 'ANULACION'
           OR v_existente.registrado_por IS DISTINCT FROM v_usuario
           OR v_existente.movimiento_anulado_id IS DISTINCT FROM p_movimiento_id
           OR v_existente.observacion IS DISTINCT FROM btrim(p_motivo) THEN
            RAISE EXCEPTION 'IDEMPOTENCY_KEY_EN_USO' USING ERRCODE = '23505';
        END IF;
        SELECT estado INTO v_estado
        FROM inventario.producto WHERE id = v_existente.producto_id;
        RETURN jsonb_build_object(
            'movimiento', to_jsonb(v_existente),
            'saldo', v_existente.saldo_resultante::text,
            'estado', v_estado
        );
    END IF;

    SELECT * INTO v_original
    FROM inventario.movimiento
    WHERE id = p_movimiento_id
    FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'MOVIMIENTO_NO_EXISTE' USING ERRCODE = 'P0002';
    END IF;
    IF v_original.tipo = 'ANULACION' THEN
        RAISE EXCEPTION 'NO_SE_PUEDE_ANULAR_UNA_ANULACION' USING ERRCODE = '22023';
    END IF;
    IF v_original.anulado_por_id IS NOT NULL THEN
        RAISE EXCEPTION 'MOVIMIENTO_YA_ANULADO' USING ERRCODE = '23505';
    END IF;

    SELECT * INTO v_producto
    FROM inventario.producto
    WHERE id = v_original.producto_id
    FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'PRODUCTO_NO_EXISTE' USING ERRCODE = 'P0002';
    END IF;

    -- Las anulaciones históricas requieren reconstruir el kardex completo.
    -- Para evitar alterar incorrectamente el costo promedio, esta función
    -- solo permite anular movimientos que sean el último movimiento del
    -- producto. Si existen movimientos posteriores, debe realizarse un
    -- ajuste controlado de inventario.
    IF EXISTS (
        SELECT 1
        FROM inventario.movimiento AS posterior
        WHERE posterior.producto_id = v_original.producto_id
          AND (posterior.ocurrido_en, posterior.id)
              > (v_original.ocurrido_en, v_original.id)
    ) THEN
        RAISE EXCEPTION
            'ANULACION_CON_MOVIMIENTOS_POSTERIORES_NO_PERMITIDA: revise el kardex y realice un ajuste de inventario';
    END IF;

    IF v_original.tipo = 'ENTRADA' THEN
        IF v_producto.stock_actual < v_original.cantidad THEN
            RAISE EXCEPTION 'STOCK_INSUFICIENTE_PARA_ANULACION' USING ERRCODE = '23514';
        END IF;
        v_nuevo_stock := v_producto.stock_actual - v_original.cantidad;
        v_nuevo_costo := v_producto.costo_promedio;

        -- Reversión del componente de costo de una compra en el promedio vigente.
        IF v_original.motivo_codigo = 'COMPRA' THEN
            IF v_nuevo_stock = 0 THEN
                v_nuevo_costo := 0;
            ELSE
                v_nuevo_costo := GREATEST(
                    0,
                    (v_producto.stock_actual * v_producto.costo_promedio
                     - v_original.cantidad * COALESCE(v_original.costo_unitario, 0))
                    / v_nuevo_stock
                );
            END IF;
        ELSIF v_nuevo_stock = 0 THEN
            v_nuevo_costo := 0;
        END IF;
    ELSE
        -- Como se exige que la salida sea el último movimiento del producto,
        -- se puede restaurar exactamente el costo promedio previo a ella.
        v_nuevo_stock := v_producto.stock_actual + v_original.cantidad;
        v_nuevo_costo := v_original.costo_promedio_anterior;
    END IF;

    UPDATE inventario.producto
    SET stock_actual = v_nuevo_stock,
        costo_promedio = v_nuevo_costo
    WHERE id = v_producto.id;
    SELECT estado INTO v_estado
    FROM inventario.producto WHERE id = v_producto.id;

    -- Se conserva el motivo original (la tabla D12 solo clasifica ENTRADA/SALIDA).
    -- La explicación de la anulación queda en observacion.
    INSERT INTO inventario.movimiento (
        producto_id, tipo, motivo_codigo, cantidad, saldo_resultante,
        costo_unitario, costo_promedio_resultante, observacion,
        registrado_por, movimiento_anulado_id, idempotency_key,
        stock_anterior, costo_promedio_anterior
    ) VALUES (
        v_original.producto_id, 'ANULACION', v_original.motivo_codigo,
        v_original.cantidad, v_nuevo_stock, v_original.costo_unitario,
        v_nuevo_costo, btrim(p_motivo), v_usuario, v_original.id,
        p_idempotency_key, v_producto.stock_actual, v_producto.costo_promedio
    ) RETURNING * INTO v_anulacion;

    UPDATE inventario.movimiento
    SET anulado_por_id = v_anulacion.id
    WHERE id = v_original.id;

    RETURN jsonb_build_object(
        'movimiento', to_jsonb(v_anulacion),
        'saldo', v_nuevo_stock::text,
        'estado', v_estado
    );
END;
$function$;

-- ---------------------------------------------------------------------------
-- 7. Protección de inmutabilidad.
-- Solo se permite completar una vez anulado_por_id, apuntando a la anulación
-- recién insertada que referencia exactamente el movimiento original.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION inventario.tg_proteger_movimiento()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $function$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'MOVIMIENTOS_NO_SE_PUEDEN_ELIMINAR';
    END IF;

    IF TG_OP = 'UPDATE'
       AND OLD.anulado_por_id IS NULL
       AND NEW.anulado_por_id IS NOT NULL
       AND NEW.id = OLD.id
       AND NEW.producto_id = OLD.producto_id
       AND NEW.tipo = OLD.tipo
       AND NEW.motivo_codigo = OLD.motivo_codigo
       AND NEW.cantidad = OLD.cantidad
       AND NEW.saldo_resultante = OLD.saldo_resultante
       AND NEW.costo_unitario IS NOT DISTINCT FROM OLD.costo_unitario
       AND NEW.costo_promedio_resultante IS NOT DISTINCT FROM OLD.costo_promedio_resultante
       AND NEW.proveedor_id IS NOT DISTINCT FROM OLD.proveedor_id
       AND NEW.observacion IS NOT DISTINCT FROM OLD.observacion
       AND NEW.registrado_por = OLD.registrado_por
       AND NEW.ocurrido_en = OLD.ocurrido_en
       AND NEW.movimiento_anulado_id IS NOT DISTINCT FROM OLD.movimiento_anulado_id
       AND NEW.idempotency_key = OLD.idempotency_key
       AND NEW.stock_anterior = OLD.stock_anterior
       AND NEW.costo_promedio_anterior = OLD.costo_promedio_anterior
       AND EXISTS (
           SELECT 1
           FROM inventario.movimiento AS anulacion
           WHERE anulacion.id = NEW.anulado_por_id
             AND anulacion.tipo = 'ANULACION'
             AND anulacion.movimiento_anulado_id = OLD.id
       ) THEN
        RETURN NEW;
    END IF;

    RAISE EXCEPTION 'MOVIMIENTOS_INMUTABLES';
END;
$function$;

CREATE TRIGGER trg_proteger_movimiento
BEFORE UPDATE OR DELETE ON inventario.movimiento
FOR EACH ROW
EXECUTE FUNCTION inventario.tg_proteger_movimiento();

