-- ============================================================================
-- 7. Tabla de relación entre roles y permisos
-- ============================================================================

CREATE TABLE IF NOT EXISTS seguridad.rol_permiso (
  rol_id       smallint NOT NULL,
  permiso_id   smallint NOT NULL,
  asignado_en  timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT rol_permiso_pk
    PRIMARY KEY (rol_id, permiso_id),

  CONSTRAINT rol_permiso_rol_fk
    FOREIGN KEY (rol_id)
    REFERENCES seguridad.rol (id),

  CONSTRAINT rol_permiso_permiso_fk
    FOREIGN KEY (permiso_id)
    REFERENCES seguridad.permiso (id)
);

COMMENT ON TABLE seguridad.rol_permiso IS
  'Relaciona los roles del sistema con sus permisos funcionales';


