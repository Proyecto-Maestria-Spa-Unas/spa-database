-- 1. Crear esquema de seguridad
CREATE SCHEMA IF NOT EXISTS seguridad;

COMMENT ON SCHEMA seguridad IS
  'Control de roles, permisos y perfiles de usuarios del sistema Spa de Uñas';

-- 2. Privilegios del esquema
REVOKE ALL ON SCHEMA seguridad FROM PUBLIC, anon;

GRANT USAGE ON SCHEMA seguridad
  TO authenticated, service_role;

-- 3. Tabla de roles
CREATE TABLE IF NOT EXISTS seguridad.rol (
  id          smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo      varchar(30) NOT NULL,
  nombre      varchar(50) NOT NULL,
  descripcion varchar(200),
  activo      boolean NOT NULL DEFAULT true,
  creado_en   timestamptz NOT NULL DEFAULT now(),
  actualizado_en timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT rol_codigo_uk UNIQUE (codigo),
  CONSTRAINT rol_nombre_uk UNIQUE (nombre),
  CONSTRAINT rol_codigo_formato
    CHECK (codigo ~ '^[A-Z_]{2,30}$')
);

COMMENT ON TABLE seguridad.rol IS
  'Roles funcionales del sistema: Administrador, Manicurista y Gerente';


-- ============================================================================
-- 4. Tabla de permisos
-- ============================================================================

CREATE TABLE IF NOT EXISTS seguridad.permiso (
  id          smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo      varchar(60) NOT NULL,
  nombre      varchar(100) NOT NULL,
  descripcion varchar(200),
  activo      boolean NOT NULL DEFAULT true,
  creado_en   timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT permiso_codigo_uk UNIQUE (codigo),
  CONSTRAINT permiso_nombre_uk UNIQUE (nombre),
  CONSTRAINT permiso_codigo_formato
    CHECK (codigo ~ '^[a-z_]+(\.[a-z_]+)+$')
);

COMMENT ON TABLE seguridad.permiso IS
  'Catálogo de los 13 permisos funcionales del sistema';

