ALTER TABLE inventario.movimiento ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON inventario.movimiento FROM PUBLIC, anon;
GRANT SELECT ON inventario.movimiento TO authenticated, service_role;
GRANT ALL ON inventario.movimiento TO service_role;
GRANT USAGE, SELECT ON SEQUENCE inventario.movimiento_id_seq TO service_role;

DROP POLICY IF EXISTS movimiento_consultar ON inventario.movimiento;
CREATE POLICY movimiento_consultar
ON inventario.movimiento
FOR SELECT
TO authenticated
USING (
    seguridad.tiene_permiso('movimiento.consultar')
    AND (
        NOT seguridad.tiene_permiso('movimiento.registrar_salida')
        OR registrado_por = (SELECT auth.uid())
        OR seguridad.tiene_permiso('movimiento.registrar_entrada')
        OR seguridad.tiene_permiso('movimiento.anular')
    )
);

