-- ════════════════════════════════════════════════════════════════════════════
--  D2 · Catálogo: categoria, unidad_medida y producto
--  Idempotente: se puede aplicar dos veces sin error (lo verifica el CI).
--  Reglas: RN-01 código único · RN-02 nombre obligatorio · RN-06 stock >= 0
--          RN-08..RN-11 estado calculado · RN-14 stock_minimo null = sin alerta
--  S2 (catálogo) lee stock_actual pero no lo escribe: lo actualiza el trigger
--  de movimientos (D7).
-- ════════════════════════════════════════════════════════════════════════════

-- ── Categorías ──────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS inventario.categoria (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre         extensions.citext NOT NULL,
  descripcion    varchar(200),
  orden          integer NOT NULL DEFAULT 0,
  activa         boolean NOT NULL DEFAULT true,
  creado_en      timestamptz NOT NULL DEFAULT now(),
  actualizado_en timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT categoria_nombre_uk     UNIQUE (nombre),
  CONSTRAINT categoria_nombre_largo  CHECK (char_length(btrim(nombre::text)) BETWEEN 2 AND 80),
  CONSTRAINT categoria_orden_positivo CHECK (orden >= 0)
);
COMMENT ON TABLE inventario.categoria IS 'Agrupa productos del inventario (HU-02). Las inactivas no aparecen en GET /categorias';

-- ── Unidades de medida ──────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS inventario.unidad_medida (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo           extensions.citext NOT NULL,
  nombre           varchar(40) NOT NULL,
  magnitud         text NOT NULL,
  admite_decimales boolean NOT NULL,
  CONSTRAINT unidad_medida_codigo_uk UNIQUE (codigo),
  CONSTRAINT unidad_medida_codigo_formato CHECK (codigo::text ~ '^[A-Z0-9_]{1,10}$'),
  CONSTRAINT unidad_medida_magnitud CHECK (magnitud IN ('CONTEO', 'VOLUMEN', 'MASA'))
);
COMMENT ON COLUMN inventario.unidad_medida.admite_decimales IS 'RN-04: si es false, las cantidades de movimientos deben ser enteras (lo valida D7)';

-- ── Productos ───────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS inventario.producto (
  id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  codigo           extensions.citext NOT NULL,
  nombre           varchar(120) NOT NULL,
  descripcion      text,
  categoria_id     integer NOT NULL REFERENCES inventario.categoria (id),
  unidad_medida_id integer NOT NULL REFERENCES inventario.unidad_medida (id),
  stock_actual     numeric(14,3) NOT NULL DEFAULT 0,
  stock_minimo     numeric(14,3),
  costo_promedio   numeric(14,4) NOT NULL DEFAULT 0,
  descontinuado    boolean NOT NULL DEFAULT false,
  estado           text GENERATED ALWAYS AS (
                     CASE
                       WHEN descontinuado                                        THEN 'DESCONTINUADO' -- RN-11
                       WHEN stock_actual <= 0                                    THEN 'AGOTADO'       -- RN-10
                       WHEN stock_minimo IS NOT NULL AND stock_actual <= stock_minimo THEN 'BAJO_STOCK' -- RN-09
                       ELSE                                                           'DISPONIBLE'    -- RN-08
                     END
                   ) STORED,
  version          integer NOT NULL DEFAULT 1,
  creado_en        timestamptz NOT NULL DEFAULT now(),
  actualizado_en   timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT producto_codigo_uk          UNIQUE (codigo),                                          -- RN-01
  CONSTRAINT producto_codigo_largo       CHECK (char_length(btrim(codigo::text)) BETWEEN 1 AND 40),
  CONSTRAINT producto_nombre_obligatorio CHECK (btrim(nombre) <> ''),                              -- RN-02
  CONSTRAINT producto_stock_no_negativo  CHECK (stock_actual >= 0),                                -- RN-06
  CONSTRAINT producto_minimo_no_negativo CHECK (stock_minimo IS NULL OR stock_minimo >= 0),       -- RN-14
  CONSTRAINT producto_costo_no_negativo  CHECK (costo_promedio >= 0),
  CONSTRAINT producto_version_positiva   CHECK (version >= 1)
);
COMMENT ON COLUMN inventario.producto.estado IS 'Calculado (RN-08..RN-11). Mismas fronteras que calcular_estado_inventario en spa-backend-api (B3)';
COMMENT ON COLUMN inventario.producto.stock_actual IS 'Solo cambia por movimientos (trigger de D7). El catálogo no lo escribe';
COMMENT ON COLUMN inventario.producto.costo_promedio IS 'Costo promedio ponderado; lo recalculan las COMPRA (D7, DEC-11)';
COMMENT ON COLUMN inventario.producto.version IS 'Bloqueo optimista: la API la compara con If-Match';

CREATE INDEX IF NOT EXISTS producto_categoria_idx ON inventario.producto (categoria_id);
CREATE INDEX IF NOT EXISTS producto_unidad_idx    ON inventario.producto (unidad_medida_id);
CREATE INDEX IF NOT EXISTS producto_estado_idx    ON inventario.producto (estado);

-- ── Sellos de actualización y versión ───────────────────────────────────────
CREATE OR REPLACE FUNCTION inventario.tg_sellar_actualizacion() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  NEW.actualizado_en := now();
  RETURN NEW;
END $$;

CREATE OR REPLACE FUNCTION inventario.tg_producto_version() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  NEW.actualizado_en := now();
  NEW.version := OLD.version + 1;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_categoria_actualizada ON inventario.categoria;
CREATE TRIGGER trg_categoria_actualizada BEFORE UPDATE ON inventario.categoria
  FOR EACH ROW EXECUTE FUNCTION inventario.tg_sellar_actualizacion();

DROP TRIGGER IF EXISTS trg_producto_version ON inventario.producto;
CREATE TRIGGER trg_producto_version BEFORE UPDATE ON inventario.producto
  FOR EACH ROW EXECUTE FUNCTION inventario.tg_producto_version();

-- ── Privilegios mínimos ─────────────────────────────────────────────────────
REVOKE ALL ON inventario.categoria, inventario.unidad_medida, inventario.producto FROM PUBLIC, anon;
GRANT SELECT, INSERT, UPDATE ON inventario.categoria TO authenticated;
GRANT SELECT ON inventario.unidad_medida TO authenticated;
GRANT SELECT, INSERT ON inventario.producto TO authenticated;
-- authenticated no puede escribir stock_actual, costo_promedio, estado ni version
GRANT UPDATE (nombre, descripcion, categoria_id, unidad_medida_id, stock_minimo, descontinuado)
  ON inventario.producto TO authenticated;
GRANT ALL ON inventario.categoria, inventario.unidad_medida, inventario.producto TO service_role;

