  ON p.codigo = asignaciones.permiso_codigo

ON CONFLICT (rol_id, permiso_id) DO NOTHING;


-- ============================================================================
-- 9. Tabla de perfiles de usuario
-- ============================================================================

CREATE TABLE IF NOT EXISTS seguridad.perfil (
  usuario_id   uuid PRIMARY KEY,
  rol_id       smallint NOT NULL,
  activo       boolean NOT NULL DEFAULT true,
  creado_en    timestamptz NOT NULL DEFAULT now(),
  actualizado_en timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT perfil_usuario_fk
    FOREIGN KEY (usuario_id)
    REFERENCES auth.users (id)
    ON DELETE RESTRICT,

  CONSTRAINT perfil_rol_fk
    FOREIGN KEY (rol_id)
    REFERENCES seguridad.rol (id)
    ON DELETE RESTRICT
);

COMMENT ON TABLE seguridad.perfil IS
  'Perfil funcional de cada usuario autenticado de Supabase';

COMMENT ON COLUMN seguridad.perfil.activo IS
  'Permite desactivar usuarios sin eliminar sus perfiles';

-- ============================================================================
-- 10. Impedir la eliminación física de perfiles
-- ============================================================================

CREATE OR REPLACE FUNCTION seguridad.tg_impedir_eliminacion_perfil()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  RAISE EXCEPTION
    'No se permite eliminar perfiles. Desactive el usuario mediante activo = false.';
END;
$$;

DROP TRIGGER IF EXISTS trg_perfil_no_eliminar
ON seguridad.perfil;

CREATE TRIGGER trg_perfil_no_eliminar
BEFORE DELETE ON seguridad.perfil
FOR EACH ROW
EXECUTE FUNCTION seguridad.tg_impedir_eliminacion_perfil();

-- ============================================================================
-- 11. Privilegios sobre perfiles
-- ============================================================================

REVOKE ALL ON seguridad.perfil
FROM PUBLIC, anon, authenticated;

GRANT SELECT, INSERT, UPDATE
ON seguridad.perfil
TO service_role;

-- ============================================================================
-- 12. Privilegios de consulta sobre roles y permisos
-- ============================================================================

REVOKE ALL ON seguridad.rol,
              seguridad.permiso,
              seguridad.rol_permiso
FROM PUBLIC, anon, authenticated;

GRANT SELECT ON seguridad.rol,
                seguridad.permiso,
                seguridad.rol_permiso
TO service_role;

-- ============================================================================
-- 13. Privilegios sobre secuencias
-- ============================================================================

GRANT USAGE, SELECT
ON ALL SEQUENCES IN SCHEMA seguridad
TO service_role;