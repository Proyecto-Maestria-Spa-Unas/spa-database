BEGIN;

-- ---------------------------------------------------------------------------
-- 0. Verificar dependencias de D6 y D12. D7 NO recrea motivo_movimiento.
-- ---------------------------------------------------------------------------
DO $check$
BEGIN
    IF to_regclass('inventario.producto') IS NULL
       OR to_regclass('inventario.unidad_medida') IS NULL
       OR to_regclass('inventario.proveedor') IS NULL
       OR to_regclass('inventario.motivo_movimiento') IS NULL
       OR to_regprocedure('seguridad.tiene_permiso(text)') IS NULL THEN
        RAISE EXCEPTION
            'DEPENDENCIA_FALTANTE: D7 requiere D6 y D12 aplicadas previamente';
    END IF;
END;
$check$;

-- Verificar que el catálogo de D12 tenga los seis códigos definidos por contrato.
DO $check$
DECLARE
    v_faltantes text;
BEGIN
    SELECT string_agg(c.codigo, ', ' ORDER BY c.codigo)
    INTO v_faltantes
    FROM (VALUES
        ('COMPRA'),
        ('AJUSTE_CONTEO'),
        ('SALDO_INICIAL'),
        ('CONSUMO_SERVICIO'),
        ('MERMA'),
        ('VENCIMIENTO')
    ) AS c(codigo)
    WHERE NOT EXISTS (
        SELECT 1
        FROM inventario.motivo_movimiento AS m
        WHERE m.codigo = c.codigo
          AND m.activo = true
    );

    IF v_faltantes IS NOT NULL THEN
        RAISE EXCEPTION
            'CATALOGO_MOTIVOS_INCOMPLETO: faltan motivos activos: %',
            v_faltantes;
    END IF;
END;
$check$;

-- ---------------------------------------------------------------------------
-- 1. Tabla de movimientos (el catálogo de motivos pertenece a D12).
-- ---------------------------------------------------------------------------
CREATE TABLE inventario.movimiento (
    id                          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id                 uuid NOT NULL
        REFERENCES inventario.producto(id) ON DELETE RESTRICT,
    tipo                        varchar(10) NOT NULL,
    motivo_codigo               varchar(30) NOT NULL
        REFERENCES inventario.motivo_movimiento(codigo) ON DELETE RESTRICT,
    cantidad                    numeric(14,3) NOT NULL,
    saldo_resultante            numeric(14,3) NOT NULL,
    costo_unitario              numeric(14,4),
    costo_promedio_resultante   numeric(14,4),
    proveedor_id                uuid
        REFERENCES inventario.proveedor(id) ON DELETE RESTRICT,
    observacion                 varchar(280),
    registrado_por              uuid NOT NULL
        REFERENCES auth.users(id) ON DELETE RESTRICT,
    ocurrido_en                 timestamptz NOT NULL DEFAULT now(),
    movimiento_anulado_id       integer
        REFERENCES inventario.movimiento(id) ON DELETE RESTRICT,
    anulado_por_id              integer
        REFERENCES inventario.movimiento(id) ON DELETE RESTRICT,
    idempotency_key             uuid NOT NULL,
    stock_anterior              numeric(14,3) NOT NULL,
    costo_promedio_anterior     numeric(14,4) NOT NULL,

    CONSTRAINT movimiento_tipo_ck
        CHECK (tipo IN ('ENTRADA', 'SALIDA', 'ANULACION')),
    CONSTRAINT movimiento_cantidad_ck CHECK (cantidad > 0),
    CONSTRAINT movimiento_saldo_ck CHECK (saldo_resultante >= 0),
    CONSTRAINT movimiento_costo_unitario_ck
        CHECK (costo_unitario IS NULL OR costo_unitario >= 0),
    CONSTRAINT movimiento_costo_promedio_ck
        CHECK (costo_promedio_resultante IS NULL OR costo_promedio_resultante >= 0),
    CONSTRAINT movimiento_stock_anterior_ck CHECK (stock_anterior >= 0),
    CONSTRAINT movimiento_costo_anterior_ck CHECK (costo_promedio_anterior >= 0),
    CONSTRAINT movimiento_observacion_ck
        CHECK (observacion IS NULL OR char_length(observacion) <= 280),
    CONSTRAINT movimiento_anulacion_referencia_ck
        CHECK (
            (tipo = 'ANULACION' AND movimiento_anulado_id IS NOT NULL)
            OR (tipo <> 'ANULACION' AND movimiento_anulado_id IS NULL)
        ),
    CONSTRAINT movimiento_idempotencia_uk UNIQUE (idempotency_key)
);

COMMENT ON TABLE inventario.movimiento IS
    'Kardex de inventario. Los registros son inmutables; las correcciones se registran mediante ANULACION.';
COMMENT ON COLUMN inventario.movimiento.idempotency_key IS
    'UUID único por solicitud para impedir operaciones duplicadas.';
COMMENT ON COLUMN inventario.movimiento.movimiento_anulado_id IS
    'Movimiento original revertido por este movimiento de tipo ANULACION.';
COMMENT ON COLUMN inventario.movimiento.anulado_por_id IS
    'Referencia al movimiento ANULACION que revirtió este registro.';

